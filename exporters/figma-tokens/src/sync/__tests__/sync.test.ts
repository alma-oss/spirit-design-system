import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

import { fontStacks } from '../../__fixtures__/source';
import { FigmaApiError } from '../../errors';
import { syncTokens } from '../sync';

describe('syncTokens', () => {
  it('requires a Figma token before writing', async () => {
    await expect(
      syncTokens({
        config: { configPath: '/repo/spirit.config.json', sources: [] },
        token: '',
      }),
    ).rejects.toThrow(FigmaApiError);
  });

  it('writes generated files and deletes anything else in out', async () => {
    const temporaryDirectory = await mkdtemp(path.join(os.tmpdir(), 'figma-tokens-sync-'));
    const out = path.join(temporaryDirectory, 'src');

    try {
      await mkdir(path.join(out, 'scss'), { recursive: true });
      await writeFile(path.join(out, 'scss', 'stale.scss'), 'gone\n');
      await writeFile(path.join(out, 'README.md'), 'keep me\n');

      const first = await syncTokens({
        config: {
          configPath: path.join(temporaryDirectory, 'spirit.config.json'),
          sources: [
            {
              brand: 'Spirit',
              fileKey: 'file',
              fontStacks,
              out,
            },
          ],
        },
        fetch: async (input) => {
          const url = String(input);

          if (url.includes('/variables/local')) {
            return Response.json({
              meta: {
                variableCollections: {
                  global: {
                    id: 'global',
                    name: 'Global tokens',
                    key: 'global',
                    defaultModeId: 'value',
                    modes: [{ modeId: 'value', name: 'Value' }],
                    variableIds: ['radius'],
                  },
                },
                variables: {
                  radius: {
                    id: 'radius',
                    name: 'radius/radius-100',
                    key: 'radius',
                    variableCollectionId: 'global',
                    resolvedType: 'FLOAT',
                    valuesByMode: { value: 4 },
                    scopes: ['CORNER_RADIUS'],
                    remote: false,
                  },
                },
              },
            });
          }

          if (url.includes('/styles')) {
            return Response.json({ meta: { styles: [] } });
          }

          return Response.json({ name: 'SPIRIT Config' });
        },
        token: 'token',
      });

      const radii = await readFile(path.join(out, 'scss/global-tokens/_radii.scss'), 'utf8');

      expect(first.sources[0].changes.some((change) => change.type === 'added')).toBe(true);
      expect(
        first.sources[0].changes.some((change) => change.file.endsWith('stale.scss') && change.type === 'deleted'),
      ).toBe(true);
      expect(
        first.sources[0].changes.some((change) => change.file.endsWith('README.md') && change.type === 'deleted'),
      ).toBe(true);
      expect(radii.startsWith('/* This file was generated by Figma')).toBe(true);
      expect(await readdir(out)).toEqual(expect.arrayContaining(['js', 'scss']));

      const dryRun = await syncTokens({
        config: {
          configPath: path.join(temporaryDirectory, 'spirit.config.json'),
          sources: [{ brand: 'Spirit', fileKey: 'file', fontStacks, out }],
        },
        dryRun: true,
        fetch: async (input) => {
          const url = String(input);

          if (url.includes('/variables/local')) {
            return Response.json({
              meta: {
                variableCollections: {
                  global: {
                    id: 'global',
                    name: 'Global tokens',
                    key: 'global',
                    defaultModeId: 'value',
                    modes: [{ modeId: 'value', name: 'Value' }],
                    variableIds: ['radius'],
                  },
                },
                variables: {
                  radius: {
                    id: 'radius',
                    name: 'radius/radius-100',
                    key: 'radius',
                    variableCollectionId: 'global',
                    resolvedType: 'FLOAT',
                    valuesByMode: { value: 8 },
                    scopes: ['CORNER_RADIUS'],
                    remote: false,
                  },
                },
              },
            });
          }

          if (url.includes('/styles')) {
            return Response.json({ meta: { styles: [] } });
          }

          return Response.json({ name: 'SPIRIT Config' });
        },
        token: 'token',
      });

      expect(dryRun.sources[0].changes.some((change) => change.type === 'updated')).toBe(true);
      expect(await readFile(path.join(out, 'scss/global-tokens/_radii.scss'), 'utf8')).toBe(radii);
    } finally {
      await rm(temporaryDirectory, { recursive: true, force: true });
    }
  });
});
